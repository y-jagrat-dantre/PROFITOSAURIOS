// Generate demo sales history for the past 30 days
export function generateDemoSales(vegetables) {
  const sales = [];
  const today = new Date();
  let id = 1;
  for (let d = 29; d >= 0; d--) {
    const date = new Date(today);
    date.setDate(date.getDate() - d);
    const dateStr = date.toISOString().split('T')[0];
    // Pick 3-5 random vegs per day
    const count = 3 + Math.floor(Math.random() * 3);
    const shuffled = [...vegetables].sort(() => Math.random() - 0.5).slice(0, count);
    shuffled.forEach(veg => {
      const qty = Math.max(1, Math.round(veg.expectedDemand * 0.6 + Math.random() * veg.expectedDemand * 0.4));
      const price = veg.sellingPrice * (0.95 + Math.random() * 0.1);
      sales.push({
        id: id++,
        date: dateStr,
        vegetableId: veg.id,
        vegetableName: veg.name,
        quantity: qty,
        sellingPrice: Math.round(price),
        purchasePrice: veg.purchasePrice,
        revenue: Math.round(qty * price),
        profit: Math.round(qty * (price - veg.purchasePrice)),
      });
    });
  }
  return sales;
}

